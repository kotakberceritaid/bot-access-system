-- Run this only in the NEW Supabase project for the cyberpunk dashboard.
-- It creates the bot_access table required by the dashboard/API and the user_roles table.
-- It does not drop or alter any existing table.

create table if not exists public.bot_access (
  id bigint generated by default as identity primary key,
  number text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  role text not null check (role in ('owner','admin')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists user_roles_single_owner
  on public.user_roles ((role)) where role = 'owner';

alter table public.bot_access enable row level security;
alter table public.user_roles enable row level security;

revoke all on public.bot_access from anon, authenticated;
revoke all on public.user_roles from anon, authenticated;
-- Server API uses the Supabase service-role key, stored only in Vercel environment variables.
